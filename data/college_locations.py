def get_college_coords(name: str) -> tuple[float, float] | None:
    """
    Look up coordinates for a California Community College by name.
    Uses case-insensitive partial matching — e.g. "Santa Monica College" matches
    the key "santa monica college". Returns None if no match found.
    """
    if not name:
        return None
    name_lower = name.lower().strip()
    # Exact match first
    if name_lower in COLLEGE_LOCATIONS:
        return COLLEGE_LOCATIONS[name_lower]
    # Partial match: check if any key is contained in the query or vice versa
    for key, coords in COLLEGE_LOCATIONS.items():
        if key in name_lower or name_lower in key:
            return coords
    return None
